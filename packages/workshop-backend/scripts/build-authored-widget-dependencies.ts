import { build } from "esbuild";
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const backendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(backendRoot, "src/generated/authored-widget-dependencies.ts");
const fixture = `import * as Refine from "@refinedev/core";
import * as React from "react";
import * as ReactDOM from "react-dom/client";
import * as Query from "@tanstack/react-query";
import * as JSXRuntime from "react/jsx-runtime";
export { Refine, React, ReactDOM, Query, JSXRuntime };`;

const result = await build({
  absWorkingDir: backendRoot,
  stdin: { contents: fixture, resolveDir: backendRoot, sourcefile: "__dependency_roots__.tsx", loader: "tsx" },
  bundle: true,
  format: "esm",
  metafile: true,
  minify: false,
  nodePaths: [path.join(backendRoot, "node_modules")],
  platform: "browser",
  treeShaking: false,
  write: false,
  logLevel: "silent",
});

const files: Record<string, string> = {};
const resolutions: Record<string, string> = {};
for (const [input, info] of Object.entries(result.metafile!.inputs)) {
  if (input === "__dependency_roots__.tsx") continue;
  const key = `/${input.replaceAll("\\", "/")}`;
  let base = path.resolve(backendRoot, input);
  let absolute = base;
  try {
    await access(absolute);
  } catch {
    // Package symlinks in the pnpm workspace may report a store path relative to the
    // repository root even though this script runs from the backend package.
    base = path.resolve(backendRoot, "../..", input);
    try {
      await access(base);
      absolute = base;
    } catch { /* try an omitted source extension below */ }
  }
  try {
    await access(absolute);
  } catch {
    // Esbuild may omit a package's source extension in metafile input keys.
    for (const extension of [".js", ".mjs", ".cjs", ".json", ".css"]) {
      try {
        await access(base + extension);
        absolute = base + extension;
        break;
      } catch { /* try the next source extension */ }
    }
  }
  files[key] = await readFile(absolute, "utf8");
  for (const imported of info.imports) {
    if (!imported.external) {
      resolutions[`${key}::${imported.original ?? imported.path}`] = `/${imported.path.replaceAll("\\", "/")}`;
    }
  }
}

const roots = Object.fromEntries([
  ["@refinedev/core", "@refinedev/core"],
  ["react", "react"],
  ["react-dom/client", "react-dom/client"],
  ["@tanstack/react-query", "@tanstack/react-query"],
  ["react/jsx-runtime", "react/jsx-runtime"],
].map(([name, id]) => {
  const resolved = import.meta.resolve(id!);
  const input = path.relative(backendRoot, new URL(resolved).pathname).replaceAll("\\", "/");
  const key = `/${input}`;
  if (!(key in files)) throw new Error(`Missing dependency root from compile closure: ${name} -> ${key}`);
  return [name!, key];
}));

const dependencyBytes = Buffer.byteLength(JSON.stringify({ files, resolutions, roots }));
const wasmBytes = (await readFile(path.join(backendRoot, "node_modules/esbuild-wasm/esbuild.wasm"))).byteLength;
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath,
  `// Generated by scripts/build-authored-widget-dependencies.ts.\n` +
  `export const authoredWidgetDependencies = ${JSON.stringify({ files, resolutions, roots })} as const;\n` +
  `export const authoredWidgetDependencyBytes = ${dependencyBytes};\n` +
  `export const authoredWidgetWasmBytes = ${wasmBytes};\n`);
console.log(`Authored widget compile closure: ${Object.keys(files).length} modules; ${dependencyBytes} bytes plus ${wasmBytes} wasm bytes`);
